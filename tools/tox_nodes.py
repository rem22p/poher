#!/usr/bin/env python3
"""Refresh src/net/tox_nodes.inc: the Tox entry nodes built into the program.

  tools/tox_nodes.py              download the public list from nodes.tox.chat
  tools/tox_nodes.py nodes.json   use an already downloaded list

Only nodes that answered the last public scan over both UDP and TCP are kept.
Host names are turned into addresses here, so the program itself never waits
for DNS: on some computers one lookup takes ten seconds.
"""
import ipaddress
import json
import socket
import sys
import time
import urllib.request
from pathlib import Path

SOURCE = "https://nodes.tox.chat/json"
DEST = Path(__file__).resolve().parent.parent / "src" / "net" / "tox_nodes.inc"
MAX_TCP_PORTS = 3


def addresses(host):
    """The host itself if it is already an address, otherwise what DNS says."""
    try:
        ipaddress.ip_address(host)
        return [host]
    except ValueError:
        pass
    try:
        found = {info[4][0] for info in socket.getaddrinfo(host, None)}
    except OSError as error:
        print(f"skipped {host}: {error}", file=sys.stderr)
        return []
    return sorted(found, key=lambda a: (":" in a, a))


def main():
    if len(sys.argv) > 1:
        data = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))
    else:
        request = urllib.request.Request(SOURCE, headers={"User-Agent": "tox-nodes-refresh"})
        with urllib.request.urlopen(request, timeout=30) as reply:
            data = json.load(reply)

    rows = []
    for node in sorted(data["nodes"], key=lambda n: (n.get("location", ""), n["public_key"])):
        if not (node.get("status_udp") and node.get("status_tcp")):
            continue
        hosts = []
        for name in (node.get("ipv4"), node.get("ipv6")):
            if not name or name == "-":
                continue
            for host in addresses(name):
                if host not in hosts:
                    hosts.append(host)
        ports = ", ".join(str(p) for p in node["tcp_ports"][:MAX_TCP_PORTS])
        for host in hosts:
            rows.append('    {"%s", %d, "%s", {%s}},  // %s'
                        % (host, node["port"], node["public_key"], ports, node.get("location", "?")))

    scan = time.strftime("%Y-%m-%d", time.gmtime(data.get("last_scan", 0)))
    text = ("// Generated by tools/tox_nodes.py from %s (scan of %s). Do not edit by hand.\n"
            "// host, UDP port, public key, TCP ports\n" % (SOURCE, scan)) + "\n".join(rows) + "\n"
    DEST.write_text(text, encoding="utf-8")
    print(f"{DEST}: {len(rows)} entries")


if __name__ == "__main__":
    main()
